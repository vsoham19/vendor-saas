import { Router, Request, Response, NextFunction } from 'express';
import { supabaseAdmin } from '../config/supabase';

const router = Router();

/**
 * POST /api/orders
 * Generates an order entry and processes any partial upfront advance payments.
 */
router.post('/', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const { customer_id, total_amount, advance_amount, payment_method } = req.body;
    const vendorId = req.vendorId;

    if (!customer_id || !total_amount) {
      return res.status(400).json({ error: 'Bad Request', message: 'Customer selection and total amount are required.' });
    }

    // Initialize the base order record
    const { data: order, error: orderErr } = await supabaseAdmin
      .from('orders')
      .insert([{
        vendor_id: vendorId,
        customer_id,
        total_amount,
        amount_paid: 0, // This will be calculated and updated by the database triggers
        status: 'pending'
      }])
      .select()
      .single();

    if (orderErr || !order) throw orderErr;

    // If an initial advance payment is provided, process it immediately
    if (advance_amount && Number(advance_amount) > 0) {
      const { error: paymentErr } = await supabaseAdmin
        .from('payments')
        .insert([{
          order_id: order.id,
          amount: advance_amount,
          payment_method: payment_method || 'Cash'
        }]);

      if (paymentErr) throw paymentErr;
    }

    // Fetch the updated balance calculations generated by database triggers
    const { data: finalOrder, error: fetchErr } = await supabaseAdmin
      .from('orders')
      .select('*')
      .eq('id', order.id)
      .single();

    if (fetchErr) throw fetchErr;
    res.status(201).json(finalOrder);
  } catch (err) {
    next(err);
  }
});

/**
 * GET /api/orders/:id
 * Fetches an individual order file. Balances are returned exactly as calculated by database triggers.
 */
router.get('/:id', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const { id } = req.params;
    const vendorId = req.vendorId;

    const { data: order, error: orderErr } = await supabaseAdmin
      .from('orders')
      .select('*, customers(name, phone)')
      .eq('id', id)
      .eq('vendor_id', vendorId)
      .single();

    if (orderErr || !order) {
      return res.status(404).json({ error: 'Not Found', message: 'Order record does not exist.' });
    }

    const { data: payments, error: paymentsErr } = await supabaseAdmin
      .from('payments')
      .select('*')
      .eq('order_id', id)
      .order('created_at', { ascending: true });

    res.status(200).json({ order, payments: payments || [] });
  } catch (err) {
    next(err);
  }
});

/**
 * POST /api/orders/:id/payments
 * Appends an immutable partial payment entry onto an active running ledger.
 */
router.post('/:id/payments', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const { id } = req.params;
    const { amount, payment_method } = req.body;
    const vendorId = req.vendorId;

    if (!amount || Number(amount) <= 0) {
      return res.status(400).json({ error: 'Bad Request', message: 'Payment volume must be greater than zero.' });
    }

    // Verify ownership structure before adding transaction records
    const { data: order, error: orderErr } = await supabaseAdmin
      .from('orders')
      .select('id, amount_outstanding')
      .eq('id', id)
      .eq('vendor_id', vendorId)
      .single();

    if (orderErr || !order) {
      return res.status(404).json({ error: 'Not Found', message: 'Target invoice record does not exist.' });
    }

    // Create the payment record
    const { error: paymentErr } = await supabaseAdmin
      .from('payments')
      .insert([{
        order_id: id,
        amount,
        payment_method: payment_method || 'UPI'
      }]);

    if (paymentErr) throw paymentErr;

    // Pull the refreshed tracking state compiled by database triggers
    const { data: updatedOrder, error: refreshErr } = await supabaseAdmin
      .from('orders')
      .select('*')
      .eq('id', id)
      .single();

    if (refreshErr) throw refreshErr;
    res.status(201).json({ message: 'Payment logged successfully', order: updatedOrder });
  } catch (err) {
    next(err);
  }
});

export default router;